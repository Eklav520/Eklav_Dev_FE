import eklavLogo from '@/assets/images/logo_black.png'

/* Eklav-branded PDF of a report table, shared by the dashboard module reports (the same layout as the
   Eklav AI assistant's exports): logo header, title and period, the table, page numbers. */

type Cell = string | number | null | undefined
type RGB = [number, number, number]

const ORANGE: RGB = [255, 122, 0]
const INK: RGB = [15, 23, 42]
const GRAY: RGB = [100, 116, 139]

const toDataUrl = (src: string) => fetch(src).then((r) => r.blob()).then((b) => new Promise<string>((resolve, reject) => {
  const fr = new FileReader()
  fr.onload = () => resolve(fr.result as string)
  fr.onerror = reject
  fr.readAsDataURL(b)
}))

export async function exportBrandedPdf({ title, subtitle, rows, fileName, reportLabel = 'STUDENT REPORT' }: {
  title: string
  subtitle?: string
  /** One object per row, keys are the column headings (the same rows the Excel export writes) */
  rows: Record<string, Cell>[]
  fileName: string
  reportLabel?: string
}) {
  const [pdfLib, tableLib, logo] = await Promise.all([
    import('jspdf'), import('jspdf-autotable'), toDataUrl(eklavLogo).catch(() => ''),
  ])
  const jsPDF = (pdfLib as any).jsPDF || pdfLib.default
  const autoTable = (tableLib as any).autoTable || tableLib.default

  const head = rows.length ? Object.keys(rows[0]) : ['No data']
  const doc = new jsPDF({ orientation: head.length > 7 ? 'landscape' : 'portrait', unit: 'mm', format: 'a4' })
  const W = doc.internal.pageSize.getWidth()
  const H = doc.internal.pageSize.getHeight()
  const M = 12
  const generated = new Date().toLocaleString('en-IN', { day: 'numeric', month: 'short', year: 'numeric', hour: 'numeric', minute: '2-digit' })

  // Header: logo, report label and date, orange rule
  if (logo) doc.addImage(logo, 'PNG', M, 9, 42, 42 * 228 / 1093)
  else { doc.setFont('helvetica', 'bold'); doc.setFontSize(18); doc.setTextColor(...ORANGE); doc.text('Eklav', M, 17) }
  doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5); doc.setTextColor(...GRAY)
  doc.text(reportLabel, W - M, 12, { align: 'right' })
  doc.text(`Generated ${generated}`, W - M, 16.5, { align: 'right' })
  doc.setDrawColor(...ORANGE); doc.setLineWidth(0.8); doc.line(M, 23, W - M, 23)

  doc.setFont('helvetica', 'bold'); doc.setFontSize(15); doc.setTextColor(...INK)
  doc.text(title, M, 32)
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9.5); doc.setTextColor(...GRAY)
  doc.text(`${subtitle ? `${subtitle}  ·  ` : ''}${rows.length} record${rows.length === 1 ? '' : 's'}`, M, 37.5)

  autoTable(doc, {
    startY: 43,
    margin: { left: M, right: M, top: 18, bottom: 16 },
    head: [head],
    body: rows.length ? rows.map((r) => head.map((k) => (r[k] === null || r[k] === undefined || r[k] === '' ? '—' : String(r[k])))) : [['No records for this filter']],
    theme: 'grid',
    styles: { font: 'helvetica', fontSize: head.length > 10 ? 6.8 : 7.6, cellPadding: 1.9, textColor: INK, lineColor: [226, 232, 240], lineWidth: 0.2, valign: 'middle' },
    headStyles: { fillColor: ORANGE, textColor: 255, fontStyle: 'bold', halign: 'center' },
    alternateRowStyles: { fillColor: [250, 250, 252] },
    columnStyles: { 0: { halign: 'center' } },
    didDrawPage: () => {
      if (doc.getNumberOfPages() > 1 && logo) {
        doc.addImage(logo, 'PNG', M, 6, 24, 24 * 228 / 1093)
        doc.setFont('helvetica', 'normal'); doc.setFontSize(8); doc.setTextColor(...GRAY)
        doc.text(title, W - M, 10, { align: 'right' })
      }
      doc.setDrawColor(226, 232, 240); doc.setLineWidth(0.3); doc.line(M, H - 11, W - M, H - 11)
      doc.setFont('helvetica', 'normal'); doc.setFontSize(7.5); doc.setTextColor(...GRAY)
      doc.text('Generated by Eklav  ·  www.eklav.in  ·  Confidential: for internal use only', M, H - 6.5)
    },
  })

  const pages = doc.getNumberOfPages()
  for (let p = 1; p <= pages; p++) {
    doc.setPage(p)
    doc.setFont('helvetica', 'normal'); doc.setFontSize(7.5); doc.setTextColor(...GRAY)
    doc.text(`Page ${p} of ${pages}`, W - M, H - 6.5, { align: 'right' })
  }
  doc.save(fileName.endsWith('.pdf') ? fileName : `${fileName}.pdf`)
}
